// Writes the build into ConchKit as Swift: Conch.app is built with
// `swift build` alone, and a resource bundle beside the executable would
// break the app's signature. The file is committed, as the settings
// page's dist/ is; CI rebuilds it and fails if it moved.
import { createHash } from "node:crypto"
import { readFileSync, writeFileSync } from "node:fs"

const js = readFileSync(new URL("../dist/conch-ui.js", import.meta.url), "utf8")
const css = readFileSync(new URL("../dist/conch-ui.css", import.meta.url), "utf8")

// A raw string's delimiter longer than any run of # in the text after a
// quote, so nothing in the build can end it.
function raw(s) {
  let n = 1
  for (const m of s.matchAll(/"(#+)/g)) n = Math.max(n, m[1].length + 1)
  const h = "#".repeat(n)
  return `${h}"""\n${s}\n"""${h}`
}

const version = createHash("sha256").update(js).update(css).digest("hex").slice(0, 12)
const out = `// Generated by ui/scripts/swift.mjs from ui/ (conch-ui): do not edit.
// Run \`make conch-ui\` after changing ui/src and commit this file.

/// conch-ui's script: React and the views, as one IIFE.
public let conchUIScript = ${raw(js)}

/// conch-ui's stylesheet.
public let conchUIStyle = ${raw(css)}

/// A hash of the two, which changes when either does.
public let conchUIVersion = "${version}"
`
writeFileSync(new URL("../../macos/Sources/ConchKit/ConchUIBundle.swift", import.meta.url), out)
console.log(`ConchUIBundle.swift: ${js.length} bytes of script, ${css.length} of style, ${version}`)
